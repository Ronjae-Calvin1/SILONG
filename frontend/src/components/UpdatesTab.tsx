import "./AlertsTabs.css";

export type UpdatesStatus = "loading" | "error" | "unavailable" | "empty" | "ready";

// What ONE update card needs to show. When the backend is connected,
// we convert its response into this shape.
export type UpdateItem = {
  id: string;
  organization: string; // e.g. "PAGASA"
  publishedAt: Date;
  summary: string;
  sourceUrl: string; // always required: every update must link to the original
  isOfficial: boolean; // true for government agencies (PAGASA, NDRRMC, ...)
};

type Props = {
  status: UpdatesStatus;
  errorMessage: string | null;
  updates?: UpdateItem[];
  onRetry: () => void;
};

function formatDateTime(d: Date): string {
  return d.toLocaleString("en-PH", { month: "short", day: "numeric", hour: "numeric", minute: "2-digit" });
}

// "PAGASA" -> "PA", "Batangas City DRRMO" -> "BC"
function initials(name: string): string {
  const words = name.trim().split(/\s+/);
  const letters = words.length > 1 ? words[0][0] + words[1][0] : name.trim().slice(0, 2);
  return letters.toUpperCase();
}

export function UpdatesTab({ status, errorMessage, updates = [], onRetry }: Props) {
  // Official sources first, then the newest first.
  const sorted = [...updates].sort(
    (a, b) => Number(b.isOfficial) - Number(a.isOfficial) || b.publishedAt.getTime() - a.publishedAt.getTime()
  );

  return (
    <div className="updates-tab">
      {status === "loading" && (
        <div className="state-box" role="status">
          <strong>Loading updates…</strong>
        </div>
      )}

      {status === "error" && (
        <div className="state-box state-box-error" role="alert">
          <strong>Couldn't load updates</strong>
          <p>{errorMessage ?? "Something went wrong. Please try again."}</p>
          <button className="state-button" onClick={onRetry}>
            Try again
          </button>
        </div>
      )}

      {status === "unavailable" && (
        <div className="state-box">
          <strong>Updates aren't connected yet</strong>
          <p>SILONG can't show summarized updates right now. For the latest news, check the official pages.</p>
          <a className="state-link" href="https://www.pagasa.dost.gov.ph/" target="_blank" rel="noopener noreferrer">
            PAGASA ↗
          </a>
          <br />
          <a className="state-link" href="https://ndrrmc.gov.ph/" target="_blank" rel="noopener noreferrer">
            NDRRMC ↗
          </a>
        </div>
      )}

      {status === "empty" && (
        <div className="state-box">
          <strong>No recent updates</strong>
          <p>There are no new updates from our sources right now.</p>
        </div>
      )}

      {status === "ready" && (
        <ul className="update-list">
          {sorted.map((u) => (
            <li className="update-card" key={u.id}>
              <span className="update-avatar" aria-hidden="true">
                {initials(u.organization)}
              </span>
              <div className="update-body">
                <div className="update-head">
                  <strong className="update-org">{u.organization}</strong>
                  {u.isOfficial && <span className="warning-badge">Official</span>}
                </div>
                <p className="warning-meta">{formatDateTime(u.publishedAt)}</p>
                <p className="update-summary">{u.summary}</p>
                <span className="ai-chip">AI-summarized</span>
                <br />
                <a className="state-link" href={u.sourceUrl} target="_blank" rel="noopener noreferrer">
                  Read Original Source ↗
                </a>
              </div>
            </li>
          ))}
        </ul>
      )}

      <p className="alerts-disclaimer">
        Summaries are generated by AI and may contain mistakes. Always read the original source.{" "}
        <strong>Official advisories come first.</strong>
      </p>
    </div>
  );
}